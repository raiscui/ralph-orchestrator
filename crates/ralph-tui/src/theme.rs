use ratatui::style::Color;

// ============================================================================
// TUI 主题色（最小可用版）
//
// 说明：
// - `Color::DarkGray`（ANSI 90）在部分终端主题下太暗，阅读吃力。
// - `Color::Gray`（ANSI 37）在部分终端主题下会接近白色，过亮刺眼。
// - 这里选用 256 色灰阶中的一个“中灰”，作为提示/标签/空态文案的默认前景色。
//
// 为什么用 Indexed 而不是 Rgb：
// - `Rgb` 依赖 truecolor，macOS Terminal.app 等环境可能不稳定；
// - `Indexed`（256 色）覆盖面更广，表现更可控。
// ============================================================================

/// 介于 `Color::DarkGray` 与 `Color::Gray` 之间的“折中灰”。
pub const MUTED_FG: Color = Color::Indexed(245);
